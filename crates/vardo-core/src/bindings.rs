//! Writes the interface's copy of the wire types (`inv:ipc-types-are-generated`).
//!
//! `cargo test` fails when `app/src/ipc/bindings.ts` is stale. Rewrite it with
//! `UPDATE_FIXTURES=1 cargo test -p vardo-core --lib bindings`.

use std::path::PathBuf;

use ts_rs::{Config, TS};

use crate::health::{Finding, Issue, Report};
use crate::model::*;
use crate::source::VaultSource;
use crate::CoreError;

fn decl<T: TS>(cfg: &Config) -> String {
    let docs = T::docs().unwrap_or_default();
    format!("{docs}export {}\n", T::decl(cfg))
}

fn render() -> String {
    // Timestamps are milliseconds and sizes are bytes, all far below 2^53.
    let cfg = Config::new().with_large_int("number");
    let decls = [
        decl::<VaultInfo>(&cfg),
        decl::<StorageWarning>(&cfg),
        decl::<StorageKind>(&cfg),
        decl::<GroupNode>(&cfg),
        decl::<EntrySummary>(&cfg),
        decl::<Field>(&cfg),
        decl::<Times>(&cfg),
        decl::<Attachment>(&cfg),
        decl::<EntryDetail>(&cfg),
        decl::<CopyResult>(&cfg),
        decl::<UnlockPhase>(&cfg),
        decl::<crate::session::Phase>(&cfg),
        decl::<FieldEdit>(&cfg),
        decl::<GeneratorOptions>(&cfg),
        decl::<SaveResult>(&cfg),
        decl::<ChangeView>(&cfg),
        decl::<ConflictView>(&cfg),
        decl::<ConflictPolicy>(&cfg),
        decl::<SyncPreview>(&cfg),
        decl::<SyncOutcome>(&cfg),
        decl::<SyncOutcomeKind>(&cfg),
        decl::<SyncWarning>(&cfg),
        decl::<SyncWarningKind>(&cfg),
        decl::<TotpCode>(&cfg),
        decl::<DriveStatus>(&cfg),
        decl::<DriveVault>(&cfg),
        decl::<HistoryVersion>(&cfg),
        decl::<VaultSource>(&cfg),
        decl::<Issue>(&cfg),
        decl::<Finding>(&cfg),
        decl::<Report>(&cfg),
        decl::<CoreError>(&cfg),
    ];
    format!(
        "// Generated by crates/vardo-core/src/bindings.rs. Do not edit.\n\n{}",
        decls.join("\n")
    )
}

#[test]
fn the_interface_bindings_are_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../app/src/ipc/bindings.ts");
    let want = render();
    if std::env::var_os("UPDATE_FIXTURES").is_some() {
        std::fs::write(&path, &want).unwrap();
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "app/src/ipc/bindings.ts is stale; run UPDATE_FIXTURES=1 cargo test -p vardo-core --lib bindings"
    );
}

#[test]
fn a_drive_source_keeps_its_snake_case_field_on_the_wire() {
    // `rename_all` on an enum renames variants, not fields, so recents files
    // already on disk hold `file_id`. The interface once sent `fileId`, which
    // Rust could not read, until these bindings were generated.
    let json = serde_json::to_value(VaultSource::GoogleDrive {
        file_id: "1AbC".into(),
        name: "v.kdbx".into(),
    })
    .unwrap();
    assert_eq!(json["file_id"], "1AbC");
    assert!(render().contains("file_id: string"));
}
